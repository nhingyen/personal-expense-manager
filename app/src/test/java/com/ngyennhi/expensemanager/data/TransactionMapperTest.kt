package com.ngyennhi.expensemanager.data

import com.ngyennhi.expensemanager.data.mapper.toDomain
import com.ngyennhi.expensemanager.data.mapper.toEntity
import com.ngyennhi.expensemanager.domain.model.Transaction
import com.ngyennhi.expensemanager.domain.model.TransactionDraft
import com.ngyennhi.expensemanager.domain.model.TransactionType
import java.time.LocalDate
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class TransactionMapperTest {
    @Test
    fun savedTransactionsRoundTripWithoutLosingFields() {
        val records = listOf(
            Transaction(7L, TransactionType.INCOME, Long.MAX_VALUE, "Salary", LocalDate.of(2024, 2, 29), null),
            Transaction(8L, TransactionType.EXPENSE, 1L, "Food", LocalDate.of(2026, 10, 19), "Lunch", walletId = 42),
        )

        records.forEach { assertEquals(it, it.toEntity().toDomain()) }
    }

    @Test
    fun newTransactionMapsToAutogeneratedIdPlaceholder() {
        val draft = TransactionDraft(TransactionType.EXPENSE, 1L, "Food", LocalDate.of(2026, 10, 19), null, walletId = 9)

        val entity = draft.toEntity()
        assertEquals(0L, entity.id)
        assertEquals(9L, entity.walletId)
        assertEquals(draft.amountVnd, entity.amountVnd)
        assertEquals(draft.date.toEpochDay(), entity.dateEpochDay)
        assertNull(entity.note)
    }
}
